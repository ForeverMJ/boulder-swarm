/**
 * R146-sym47 — group-invariant rank-47 probe for 4x4x4 matrix multiplication
 * over F_2 (AlphaTensor parity target: rank <= 47).
 *
 * WHY THIS LANE
 * Every earlier rank-47 lane perturbs a 49-term anchor by drop-k / add-(k-2)
 * moves or walks a support one axis at a time. This lane is disjoint by
 * construction: it only looks at 47-term supports that are invariant under a
 * nontrivial subgroup G of cell permutations acting DIAGONALLY on the three
 * tensor axes (the same permutation on u, v and w). A G-invariant support is a
 * disjoint union of G-orbits on triples, so the 47 terms are counted in orbit
 * blocks and the free variables are cut from 47 terms to whole orbits. An
 * invariant SCHEME also has constant coefficient on each orbit; over F_2 the
 * only nonzero invariant choice is coefficient 1 on whole orbits, so the exact
 * solve is done on orbit columns, not just on the 47 individual terms.
 *
 * GROUPS PROBED (all generated by explicit 16-cell permutations)
 *   - S4-diagonal: all 24 coordinate permutations of the 4 indices, applied by
 *     simultaneous conjugation M -> P M P^T on every axis. This is an algebra
 *     automorphism, so it fixes the matmul tensor.
 *   - C4-diagonal: the cyclic 4-cycle subgroup of S4 (order 4). Same action,
 *     same tensor-fixing property.
 *   - BT-diagonal: the 2+2 block swap [2,3,0,1] together with the matrix
 *     transpose involution, acting on all three axes. The block swap fixes the
 *     tensor, but the transpose does NOT: transpose is an anti-automorphism,
 *     and only the transpose+axis-swap combinations preserve the product. The
 *     probe therefore measures and reports this obstruction instead of hiding
 *     it; no BT-invariant scheme can exist while the target is not BT-fixed.
 *
 * TARGET FIXEDNESS IS CHECKED, NOT ASSUMED
 * `targetFixedBy` re-derives, entry by entry, whether a group element fixes the
 * 4096-entry target. The control gates require S4 and C4 to fix it and require
 * the transpose involution to fail with an explicit witness entry.
 *
 * PROVENANCE / FIELD DISCIPLINE
 * F_2 throughout (verifyMod2 is the equality decision; verify is used only as
 * the integer-exact gate for a would-be witness). No AlphaTensor tensor is
 * read, imported or embedded. The only anchors are the repo's own two-level
 * Strassen 49-term construction (imported from R140_algsupports, hash
 * f4640c18) and the repo's known INCONSISTENT R100 ILS control masks
 * (hash 6098903c), both re-derived here rather than trusted.
 *
 * FILE OWNERSHIP
 * attempts/R146_sym47.ts, .test.ts, .ndjson, .json and the optional
 * _scheme.ts only. No other file is modified.
 *
 * HONESTY / BOUNDED NULL
 * The enumeration is bounded twice: (a) the candidate pool is the G-orbit
 * closure of the exact-49 floor (supports outside that closure are named as
 * untouched), and (b) at most `sampleLimit` orbit unions are exact-solved per
 * group. The artifact reports the exact orbit-subset class size, the number
 * enumerated, the fraction of the enumerated set exact-solved, and the
 * fraction of the class enumerated. A bounded null is not an impossibility
 * claim for the untouched classes.
 *
 * Usage: bun src/matmul/attempts/R146_sym47.ts [sampleLimit] [seed]
 */

