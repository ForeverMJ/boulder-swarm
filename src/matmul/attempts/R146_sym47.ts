/**
 * Non-vacuity control. A rank-2 toy tensor is planted from two triples that
 * form one orbit under the transpose involution. The orbit bookkeeping must
 * ADMIT it (invariant support, orbit-constant solve consistent, produced
 * tensor equals the planted toy tensor) and must REJECT the non-invariant
 * singleton.
 */
export function toyAdmission(): ToyControl {
  const toyGroup: Group = { name: "toy-transpose", elements: groupClosure([TRANSPOSE]) }
  const cell = (i: number, j: number): number => i * PROBLEM_N + j
  const a: Mask = [1 << cell(0, 1), 1 << cell(1, 0), 1 << cell(0, 0)]
  const b = actTriple(a, TRANSPOSE)
  const support = [a, b]
  const toyTarget = sumTensors(support)
  const orbits = orbitPartition(support, toyGroup)
  const invariant = isInvariant(support, toyGroup)
  const solve = solveOrbitCoeffs(orbits, toyTarget)
  let admitted = false
  let f2Exact = false
  if (solve.consistent && solve.solution !== null) {
    const included = orbits.filter((_, i) => (solve.solution?.[i] ?? 0) === 1)
    const produced = sumTensors(included.flatMap((o) => [...o]))
    let same = true
    for (let i = 0; i < TENSOR; i++) {
      if ((produced[i] ?? 0) !== (toyTarget[i] ?? 0)) same = false
    }
    admitted = same && included.length > 0
    f2Exact = same
  }
  const singleton: Orbit[] = [[a]]
  const singletonSolve = solveOrbitCoeffs(singleton, toyTarget)
  return {
    targetRank: support.length,
    orbitSignature: orbitSignature(support, toyGroup),
    invariant,
    admitted,
    f2Exact,
    singletonAdmitted: singletonSolve.consistent,
  }
}

