type VerifiedScheme = {
  readonly rank: number
  readonly f2Exact: boolean
  readonly integerExact: boolean
  readonly scheme: Scheme
}

function verifiedScheme(terms: readonly Mask[]): VerifiedScheme {
  const scheme = masksToScheme(terms)
  const f2 = verifyMod2(scheme)
  const intv = verify(scheme)
  return {
    rank: scheme.triples.length,
    f2Exact: f2.correct && f2.mismatches === 0,
    integerExact: intv.correct && intv.mismatches === 0,
    scheme,
  }
}

function makeRow(
  group: Group,
  targetFixed: boolean,
  support: readonly Mask[],
): { row: SupportRow; invariantCandidate: Witness | null; freeCandidate: Witness | null } {
  const invariant = isInvariant(support, group)
  const signature = invariant ? orbitSignature(support, group) : []
  const axis = axisConsistency(support)
  const allOnesMismatch = mismatchF2(support)
  const independentMismatch = verifyExactIndependent(support)
  const freeSolve = solveSupportCoeffs(support)
  const supportOrbits = invariant ? orbitPartition(support, group) : []
  const orbitSolve = invariant
    ? solveOrbitCoeffs(supportOrbits)
    : { consistent: false, variables: 0, solution: null }

  let freeIncludedRank: number | null = null
  let freeF2Exact = false
  let freeIntegerExact = false
  let freeCandidate: Witness | null = null
  if (freeSolve.consistent && freeSolve.solution !== null) {
    const included = support.filter((_, i) => (freeSolve.solution?.[i] ?? 0) === 1)
    const verified = verifiedScheme(included)
    freeIncludedRank = verified.rank
    freeF2Exact = verified.f2Exact
    freeIntegerExact = verified.integerExact
    if (verified.f2Exact && verified.integerExact && verified.rank <= TARGET_RANK) {
      freeCandidate = {
        group: group.name,
        supportHash: hashSupport(support),
        rank: verified.rank,
        invariant: false,
        scheme: verified.scheme,
      }
    }
  }

  let includedRank: number | null = null
  let f2Exact = false
  let integerExact = false
  let invariantCandidate: Witness | null = null
  if (orbitSolve.consistent && orbitSolve.solution !== null) {
    const included = supportOrbits.filter((_, i) => (orbitSolve.solution?.[i] ?? 0) === 1)
    const verified = verifiedScheme(included.flatMap((o) => [...o]))
    includedRank = verified.rank
    f2Exact = verified.f2Exact
    integerExact = verified.integerExact
    if (verified.f2Exact && verified.integerExact && verified.rank <= TARGET_RANK) {
      invariantCandidate = {
        group: group.name,
        supportHash: hashSupport(support),
        rank: verified.rank,
        invariant: true,
        scheme: verified.scheme,
      }
    }
  }

  return {
    row: {
      kind: "support",
      group: group.name,
      groupOrder: group.elements.length,
      targetFixed,
      rank: support.length,
      orbitSignature: signature,
      supportHash: hashSupport(support),
      invariant,
      axisConsistent: axis,
      allOnesMismatch,
      independentMismatch,
      freeConsistent: freeSolve.consistent,
      orbitConsistent: orbitSolve.consistent,
      includedRank,
      f2Exact,
      integerExact,
      freeIncludedRank,
      freeF2Exact,
      freeIntegerExact,
    },
    invariantCandidate,
    freeCandidate,
  }
}

export function runProbe(opts?: ProbeOptions): ProbeResult {
  const sampleLimit = opts?.sampleLimit ?? DEFAULT_SAMPLE_LIMIT
  const seed = opts?.seed ?? DEFAULT_SEED
  const write = opts?.write ?? false
  const verbose = opts?.verbose ?? false

  const floor = floorControl()
  const refuted = refutedControl()
  const toy = toyAdmission()
  const obstruction = nonFixedWitness(GROUP_BT)

  const floorSeeds = twoLevelStrassen4().map((v) => [v.u, v.v, v.w] as Mask)
  const seeds = augmentedSeedTriples()
  const groups: GroupStat[] = []
  const rows: SupportRow[] = []
  let witness: Witness | null = null

  GROUPS.forEach((group, gi) => {
    const targetFixed = targetFixedByGroup(group)
    const floorPool = buildPool(floorSeeds, group)
    const floorOrbits = orbitPartition(floorPool, group)
    const floorClosureClassTotal = countOrbitSubsets(
      floorOrbits.map((o) => o.length),
      TARGET_RANK,
    )
    const pool = buildPool(seeds, group)
    const orbits = orbitPartition(pool, group)
    const sizes = orbits.map((o) => o.length)
    const classTotal = countOrbitSubsets(sizes, TARGET_RANK)
    const supports = sampleOrbitSupports(orbits, TARGET_RANK, sampleLimit, seed + gi * 1009)
    let freeConsistent = 0
    let orbitConsistent = 0
    let exactSolved = 0
    for (const support of supports) {
      const { row, invariantCandidate, freeCandidate } = makeRow(group, targetFixed, support)
      rows.push(row)
      exactSolved++
      if (row.freeConsistent) freeConsistent++
      if (row.orbitConsistent) orbitConsistent++
      if (invariantCandidate !== null) witness = invariantCandidate
      else if (freeCandidate !== null && witness === null) witness = freeCandidate
    }
    const enumerated = supports.length
    groups.push({
      name: group.name,
      order: group.elements.length,
      targetFixed,
      poolSize: pool.length,
      orbitCount: orbits.length,
      orbitSizes: orbitSizeHistogram(orbits),
      classTotal: classTotal.toString(),
      floorClosurePoolSize: floorPool.length,
      floorClosureOrbitCount: floorOrbits.length,
      floorClosureClassTotal: floorClosureClassTotal.toString(),
      enumerated,
      exactSolved,
      freeConsistent,
      orbitConsistent,
      fractionExactSolved: enumerated === 0 ? null : exactSolved / enumerated,
      fractionClassEnumerated: classTotal === 0n ? null : enumerated / Number(classTotal),
      fractionConsistent: enumerated === 0 ? null : orbitConsistent / enumerated,
    })
    if (verbose) {
      console.log(
        `[R146] ${group.name}: order=${group.elements.length} pool=${pool.length} orbits=${orbits.length} class=${classTotal} sampled=${enumerated} orbitConsistent=${orbitConsistent}`,
      )
    }
  })

  const result: ProbeResult = {
    taskId: TASK_ID,
    field: FIELD,
    targetRank: TARGET_RANK,
    floorRank: FLOOR_RANK,
    groups,
    rows,
    controls: { floor, refuted, toy, obstruction },
    witness,
    untouchedClasses: UNTOUCHED_CLASSES,
    verified:
      floor.f2Exact &&
      floor.hash === FLOOR_HASH &&
      floor.coefficientConsistent &&
      floor.axis.u &&
      floor.axis.v &&
      floor.axis.w &&
      refuted.refuted &&
      toy.invariant &&
      toy.admitted &&
      toy.f2Exact &&
      !toy.singletonAdmitted &&
      obstruction !== null &&
      obstruction.want !== obstruction.got,
  }

  if (write) writeArtifacts(result)
  return result
}

