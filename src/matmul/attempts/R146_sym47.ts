function writeArtifacts(result: ProbeResult): void {
  writeFileSync(NDJSON_PATH, "", "utf8")
  const push = (row: unknown): void => {
    appendFileSync(NDJSON_PATH, `${JSON.stringify(row)}\n`, "utf8")
  }
  push({ kind: "start", taskId: result.taskId, field: result.field, targetRank: result.targetRank })
  push({ kind: "control", name: "floor", ...result.controls.floor })
  push({ kind: "control", name: "refuted", ...result.controls.refuted })
  push({ kind: "control", name: "toy", ...result.controls.toy })
  push({ kind: "control", name: "obstruction", ...(result.controls.obstruction ?? {}) })
  for (const g of result.groups) push({ kind: "group", ...g })
  for (const r of result.rows) push(r)
  push({
    kind: "verdict",
    taskId: result.taskId,
    verdict: result.witness !== null ? "WITNESS-47" : "BOUNDED-NULL",
    witness: result.witness === null ? null : { group: result.witness.group, hash: result.witness.supportHash, rank: result.witness.rank, invariant: result.witness.invariant },
    controlsVerified: result.verified,
  })

  const summary = {
    taskId: result.taskId,
    round: ROUND,
    field: result.field,
    problemN: PROBLEM_N,
    targetRank: result.targetRank,
    floorRank: result.floorRank,
    floorHash: FLOOR_HASH,
    verdict: result.witness !== null ? "WITNESS-47" : "BOUNDED-NULL",
    controls: result.controls,
    groups: result.groups,
    candidates: result.rows,
    witness:
      result.witness === null
        ? null
        : { group: result.witness.group, hash: result.witness.supportHash, rank: result.witness.rank, invariant: result.witness.invariant },
    untouchedClasses: result.untouchedClasses,
    note:
      "The candidate pool is the G-orbit closure of the exact-49 two-level-Strassen floor plus every triple of the simple-mask family (single cells, rows, columns, 2x2 blocks, all-ones). An invariant support is an orbit union with total size 47; classTotal is the exact number of such unions, enumerated is the bounded seeded sample, and exactSolved counts the samples on which the orbit-column F_2 solve was run. floorClosureClassTotal is the analogous exact count when only the floor seed is used. A bounded null is not an impossibility claim for the untouched classes. BT-diagonal is target-obstructed because the transpose involution is an anti-automorphism and does not fix the matmul tensor; the probe measures this rather than assuming it.",
    generatedAt: new Date().toISOString(),
  }
  writeFileSync(JSON_PATH, `${JSON.stringify(summary, null, 2)}\n`, "utf8")

  if (result.witness !== null) writeSchemeFile(result.witness)
}

function writeSchemeFile(witness: Witness): void {
  const triples = witness.scheme.triples.map((t) => {
    const u = t.u.map((x) => String(x)).join(",")
    const v = t.v.map((x) => String(x)).join(",")
    const w = t.w.map((x) => String(x)).join(",")
    return `    { u: [${u}], v: [${v}], w: [${w}] },`
  })
  const body = [
    `/** R146 exact ship: ${witness.invariant ? `${witness.group}-invariant ` : ""}rank-${witness.rank} scheme (support ${witness.supportHash}). */`,
    `import type { Scheme } from "../types"`,
    `export const scheme: Scheme = {`,
    `  n: ${PROBLEM_N},`,
    `  triples: [`,
    ...triples,
    `  ],`,
    `}`,
    ``,
  ].join("\n")
  writeFileSync(SCHEME_PATH, body, "utf8")
}

/** Read the JSON summary if a previous run wrote it (null when absent/corrupt). */
