export function actMask(mask: number, sig: CellPerm): number {
  let out = 0
  for (let c = 0; c < DIM; c++) {
    if (((mask >>> c) & 1) !== 0) out |= 1 << (sig[c] ?? c)
  }
  return out
}

export function actTriple(t: Mask, sig: CellPerm): Mask {
  return [actMask(t[0], sig), actMask(t[1], sig), actMask(t[2], sig)]
}

/** Entry-by-entry check that a cell permutation fixes the matmul tensor. */
export function targetFixedBy(sig: CellPerm): boolean {
  for (let a = 0; a < DIM; a++) {
    for (let b = 0; b < DIM; b++) {
      for (let c = 0; c < DIM; c++) {
        const want = targetAt(a, b, c)
        const got = targetAt(sig[a] ?? a, sig[b] ?? b, sig[c] ?? c)
        if (want !== got) return false
      }
    }
  }
  return true
}

export function targetFixedByGroup(group: Group): boolean {
  return group.elements.every(targetFixedBy)
}

export type NonFixedWitness = {
  readonly sig: CellPerm
  readonly triple: readonly [number, number, number]
  readonly mapped: readonly [number, number, number]
  readonly want: number
  readonly got: number
}

/** First explicit entry that a generator moves off the target (null when fixed). */
export function nonFixedWitness(group: Group): NonFixedWitness | null {
  for (const sig of group.elements) {
    for (let a = 0; a < DIM; a++) {
      for (let b = 0; b < DIM; b++) {
        for (let c = 0; c < DIM; c++) {
          const want = targetAt(a, b, c)
          const ma = sig[a] ?? a
          const mb = sig[b] ?? b
          const mc = sig[c] ?? c
          const got = targetAt(ma, mb, mc)
          if (want !== got) {
            return {
              sig,
              triple: [a, b, c],
              mapped: [ma, mb, mc],
              want,
              got,
            }
          }
        }
      }
    }
  }
  return null
}

/* ------------------------------------------------------------ orbit machinery */

export function buildPool(seeds: readonly Mask[], group: Group): Mask[] {
  const pool = new Map<string, Mask>()
  for (const t of seeds) {
    for (const g of group.elements) {
      const a = actTriple(t, g)
      pool.set(tripleKey(a), a)
    }
  }
  return [...pool.values()].sort((a, b) => compareKeys(tripleKey(a), tripleKey(b)))
}

export function orbitPartition(pool: readonly Mask[], group: Group): Orbit[] {
  const present = new Set(pool.map(tripleKey))
  const visited = new Set<string>()
  const orbits: Orbit[] = []
  const sorted = [...pool].sort((a, b) => compareKeys(tripleKey(a), tripleKey(b)))
  for (const t of sorted) {
    const tk = tripleKey(t)
    if (visited.has(tk)) continue
    const seen = new Map<string, Mask>()
    for (const g of group.elements) {
      const a = actTriple(t, g)
      const k = tripleKey(a)
      if (!present.has(k)) throw new Error(`orbit escaped pool at ${k}`)
      seen.set(k, a)
    }
    for (const k of seen.keys()) visited.add(k)
    orbits.push([...seen.values()].sort((a, b) => compareKeys(tripleKey(a), tripleKey(b))))
  }
  return orbits
}

export function isInvariant(support: readonly Mask[], group: Group): boolean {
  const keys = new Set(support.map(tripleKey))
  for (const g of group.elements) {
    for (const t of support) {
      if (!keys.has(tripleKey(actTriple(t, g)))) return false
    }
  }
  return true
}

export function orbitSignature(support: readonly Mask[], group: Group): number[] {
  return orbitPartition(support, group)
    .map((o) => o.length)
    .sort((a, b) => a - b)
}

/** Exact number of orbit unions whose sizes sum to `target`. */
export function countOrbitSubsets(sizes: readonly number[], target: number): bigint {
  const dp = new Array<bigint>(target + 1).fill(0n)
  dp[0] = 1n
  for (const s of sizes) {
    if (s <= 0 || s > target) continue
    for (let x = target; x >= s; x--) {
      const prev = dp[x - s]
      if (prev !== undefined) dp[x] = (dp[x] ?? 0n) + prev
    }
  }
  return dp[target] ?? 0n
}

/** mulberry32, same PRNG family as the other M8 rounds. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/**
 * Deterministic bounded enumeration of invariant supports: orbit indices are
 * shuffled once with the seeded PRNG, then a suffix-feasibility DP guides an
 * include-first DFS over whole orbits. Only unions whose sizes sum exactly to
 * `target` are emitted; the first `limit` are returned. A node cap keeps the
 * walk bounded and is reported through a short return, never silently ignored.
 */
export function sampleOrbitSupports(
  orbits: readonly Orbit[],
  target: number,
  limit: number,
  seed: number,
): Mask[][] {
  if (limit <= 0 || target < 0) return []
  const rnd = mulberry32(seed)
  const order = orbits.map((_, i) => i)
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1))
    const oi = order[i]
    const oj = order[j]
    if (oi === undefined || oj === undefined) continue
    order[i] = oj
    order[j] = oi
  }
  const shuffled = order
    .map((i) => orbits[i])
    .filter((o): o is Orbit => o !== undefined)
  const n = shuffled.length
  const can: boolean[][] = Array.from({ length: n + 1 }, () =>
    new Array<boolean>(target + 1).fill(false),
  )
  const last = can[n]
  if (last !== undefined) last[0] = true
  for (let i = n - 1; i >= 0; i--) {
    const sz = shuffled[i]?.length ?? 0
    const cur = can[i]
    const next = can[i + 1]
    if (cur === undefined || next === undefined) continue
    for (let s = 0; s <= target; s++) {
      cur[s] = (next[s] ?? false) || (s >= sz && (next[s - sz] ?? false))
    }
  }
  const out: Mask[][] = []
  const chosen: Orbit[] = []
  let nodes = 0
  const nodeCap = 2_000_000
  const dfs = (i: number, rem: number): void => {
    if (out.length >= limit || nodes > nodeCap) return
    nodes++
    if (rem === 0) {
      out.push(chosen.flatMap((o) => [...o]))
      return
    }
    if (i >= n) return
    const row = can[i]
    if (row === undefined || !(row[rem] ?? false)) return
    const orb = shuffled[i]
    if (orb === undefined) return
    const sz = orb.length
    if (sz <= rem && (can[i + 1]?.[rem - sz] ?? false)) {
      chosen.push(orb)
      dfs(i + 1, rem - sz)
      chosen.pop()
    }
    if (can[i + 1]?.[rem] ?? false) dfs(i + 1, rem)
  }
  dfs(0, target)
  return out
}

/**
 * Structurally natural 4x4 masks: single cells, full rows, full columns, the
 * three 2x2 blocks anchored at even coordinates, and the all-ones matrix. This
 * is the second seed family; it is deliberately sparse/structured, not random.
 */
export function simpleMasks(): number[] {
  const out = new Set<number>()
  const cell = (i: number, j: number): number => i * PROBLEM_N + j
  for (let c = 0; c < DIM; c++) out.add(1 << c)
  for (let i = 0; i < PROBLEM_N; i++) {
    let row = 0
    let col = 0
    for (let j = 0; j < PROBLEM_N; j++) {
      row |= 1 << cell(i, j)
      col |= 1 << cell(j, i)
    }
    out.add(row)
    out.add(col)
  }
  out.add(0xffff)
  for (const bi of [0, 2]) {
    for (const bj of [0, 2]) {
      let m = 0
      for (let i = 0; i < 2; i++) {
        for (let j = 0; j < 2; j++) m |= 1 << cell(bi + i, bj + j)
      }
      out.add(m)
    }
  }
  return [...out].sort((a, b) => a - b)
}

/** Floor triples plus every triple of the simple-mask family. */
export function augmentedSeedTriples(): Mask[] {
  const seeds = twoLevelStrassen4().map((v) => [v.u, v.v, v.w] as Mask)
  const masks = simpleMasks()
  for (const u of masks) {
    for (const v of masks) {
      for (const w of masks) seeds.push([u, v, w])
    }
  }
  return seeds
}

export function orbitSizeHistogram(orbits: readonly Orbit[]): Record<string, number> {
  const hist: Record<string, number> = {}
  for (const o of orbits) {
    const k = String(o.length)
    hist[k] = (hist[k] ?? 0) + 1
  }
  return hist
}

