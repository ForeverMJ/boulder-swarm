/* ------------------------------------------------------------ target tensor */

function targetVector(): Uint8Array {
  const out = new Uint8Array(TENSOR)
  for (let i = 0; i < PROBLEM_N; i++) {
    for (let j = 0; j < PROBLEM_N; j++) {
      for (let k = 0; k < PROBLEM_N; k++) {
        const a = i * PROBLEM_N + j
        const b = j * PROBLEM_N + k
        const c = i * PROBLEM_N + k
        out[(a * DIM + b) * DIM + c] = 1
      }
    }
  }
  return out
}

export const TARGET = targetVector()

export function targetAt(a: number, b: number, c: number): number {
  return TARGET[(a * DIM + b) * DIM + c] ?? 0
}

/* ------------------------------------------------------------ vector helpers */

export function bits(mask: number): number[] {
  const out: number[] = []
  for (let p = 0; p < DIM; p++) if (((mask >>> p) & 1) !== 0) out.push(p)
  return out
}

export function popcount(mask: number): number {
  let n = 0
  let m = mask >>> 0
  while (m !== 0) {
    m &= m - 1
    n++
  }
  return n
}

/** Campaign FNV-1a hash over the mask stream in the order given. */
export function hashMasks(masks: readonly Mask[]): string {
  let h = 0x811c9dc5
  for (const t of masks) {
    for (const x of t) {
      h ^= (x & 0xffff) + 0x9e37
      h = Math.imul(h, 0x01000193) >>> 0
    }
  }
  return (h >>> 0).toString(16).padStart(8, "0")
}

function compareKeys(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0
}

export function tripleKey(t: Mask): string {
  return `${t[0]},${t[1]},${t[2]}`
}

export function supportKey(support: readonly Mask[]): string {
  return support
    .map(tripleKey)
    .sort(compareKeys)
    .join("|")
}

/** Order-independent support hash (triples sorted by canonical key). */
export function hashSupport(support: readonly Mask[]): string {
  const sorted = [...support].sort((a, b) => compareKeys(tripleKey(a), tripleKey(b)))
  return hashMasks(sorted)
}

/* ------------------------------------------------------------ tensor algebra */

export function termTensor(t: Mask): Uint8Array {
  const out = new Uint8Array(TENSOR)
  const us = bits(t[0])
  const vs = bits(t[1])
  const ws = bits(t[2])
  for (const a of us) {
    for (const b of vs) {
      const base = (a * DIM + b) * DIM
      for (const c of ws) {
        out[base + c] = ((out[base + c] ?? 0) ^ 1) & 1
      }
    }
  }
  return out
}

export function xorTensorInto(dst: Uint8Array, src: Uint8Array): void {
  for (let i = 0; i < TENSOR; i++) dst[i] = ((dst[i] ?? 0) ^ (src[i] ?? 0)) & 1
}

export function sumTensors(terms: readonly Mask[]): Uint8Array {
  const out = new Uint8Array(TENSOR)
  for (const t of terms) xorTensorInto(out, termTensor(t))
  return out
}

export function mismatchAgainst(support: readonly Mask[], target: Uint8Array): number {
  const got = sumTensors(support)
  let mm = 0
  for (let i = 0; i < TENSOR; i++) if ((got[i] ?? 0) !== (target[i] ?? 0)) mm++
  return mm
}

export function mismatchF2(support: readonly Mask[]): number {
  return mismatchAgainst(support, TARGET)
}

export function masksToScheme(support: readonly Mask[]): Scheme {
  const triples: Triple[] = support.map((m) => {
    const u = new Array<number>(DIM).fill(0)
    const v = new Array<number>(DIM).fill(0)
    const w = new Array<number>(DIM).fill(0)
    for (const p of bits(m[0])) u[p] = 1
    for (const p of bits(m[1])) v[p] = 1
    for (const p of bits(m[2])) w[p] = 1
    return { u, v, w }
  })
  return { n: PROBLEM_N, triples }
}

export function verifyExactIndependent(support: readonly Mask[]): number {
  return verifyMod2(masksToScheme(support)).mismatches
}

/* ------------------------------------------------------------ exact F_2 Gauss */

/**
 * Exact F_2 Gauss-Jordan over packed 32-bit coefficient rows. This is the
 * landed campaign shape (R100_snap_spark / R107_drain49c / R140_algsupports),
 * reused here rather than reinvented. Returns a particular solution with free
 * variables set to 0, or null when inconsistent.
 */
export function gaussSolve(nvars: number, rows: readonly CoefRow[]): number[] | null {
  const words = Math.ceil(nvars / 32)
  const m = rows.map((r) => ({ coef: [...r.coef], rhs: r.rhs }))
  const where = new Array<number>(nvars).fill(-1)
  let row = 0
  for (let col = 0; col < nvars && row < m.length; col++) {
    let sel = -1
    for (let i = row; i < m.length; i++) {
      const mr = m[i]
      if (mr !== undefined && (((mr.coef[col >> 5] ?? 0) >> (col & 31)) & 1) !== 0) {
        sel = i
        break
      }
    }
    if (sel < 0) continue
    const tmp = m[sel]
    const cur = m[row]
    if (tmp === undefined || cur === undefined) continue
    m[sel] = cur
    m[row] = tmp
    where[col] = row
    for (let i = 0; i < m.length; i++) {
      if (i === row) continue
      const ri = m[i]
      const rr = m[row]
      if (ri === undefined || rr === undefined) continue
      if ((((ri.coef[col >> 5] ?? 0) >> (col & 31)) & 1) !== 0) {
        for (let k = 0; k < words; k++) ri.coef[k] = ((ri.coef[k] ?? 0) ^ (rr.coef[k] ?? 0)) >>> 0
        ri.rhs ^= rr.rhs
      }
    }
    row++
  }
  for (let i = row; i < m.length; i++) {
    const ri = m[i]
    if (ri === undefined) continue
    let allZero = true
    for (let k = 0; k < words; k++) if ((ri.coef[k] ?? 0) !== 0) allZero = false
    if (allZero && ri.rhs !== 0) return null
  }
  const sol = new Array<number>(nvars).fill(0)
  for (let col = 0; col < nvars; col++) {
    const w = where[col] ?? -1
    if (w >= 0) {
      const mr = m[w]
      sol[col] = mr === undefined ? 0 : mr.rhs
    } else sol[col] = 0
  }
  return sol
}

/**
 * Solve `sum_c x_c * columns[c] = target` over F_2. Columns are 4096-cell
 * tensors; x_c are the free coefficients. This is the exact coefficient solve
 * used by the R100/R107/R140 lanes, expressed generically so it can solve both
 * per-term supports and per-orbit (invariant) supports.
 */
export function solveTensorColumns(
  columns: readonly Uint8Array[],
  target: Uint8Array,
): SolveOutcome {
  const nvars = columns.length
  const words = Math.ceil(nvars / 32)
  const rows: { coef: number[]; rhs: number }[] = []
  for (let cell = 0; cell < TENSOR; cell++) {
    const rhs = target[cell] ?? 0
    let coef: number[] | null = null
    for (let c = 0; c < nvars; c++) {
      const col = columns[c]
      if (col !== undefined && (col[cell] ?? 0) !== 0) {
        if (coef === null) coef = new Array<number>(words).fill(0)
        coef[c >> 5] = ((coef[c >> 5] ?? 0) | (1 << (c & 31))) >>> 0
      }
    }
    if (coef !== null || rhs !== 0) {
      rows.push({ coef: coef ?? new Array<number>(words).fill(0), rhs })
    }
  }
  const solution = gaussSolve(nvars, rows)
  return { consistent: solution !== null, variables: nvars, solution }
}

export function solveSupportCoeffs(
  support: readonly Mask[],
  target: Uint8Array = TARGET,
): SolveOutcome {
  return solveTensorColumns(
    support.map((t) => termTensor(t)),
    target,
  )
}

export function solveOrbitCoeffs(orbits: readonly Orbit[], target: Uint8Array = TARGET): SolveOutcome {
  return solveTensorColumns(
    orbits.map((o) => sumTensors(o)),
    target,
  )
}

/**
 * Per-axis exact solve on the fixed support (landed R107 shape): for each axis
 * coordinate f, solve the 256-cell linear system in the 47 fixed-term variables
 * with the other two axes fixed. All 16 slices of all three axes must be
 * consistent; otherwise the fixed support is refuted.
 */
export function axisConsistency(support: readonly Mask[]): AxisFlags {
  const R = support.length
  const words = Math.ceil(R / 32)
  const flags: boolean[] = []
  for (const axis of [0, 1, 2] as const) {
    let ok = true
    for (let f = 0; f < DIM && ok; f++) {
      const rows: { coef: number[]; rhs: number }[] = []
      for (let g1 = 0; g1 < DIM; g1++) {
        for (let g2 = 0; g2 < DIM; g2++) {
          let a = 0
          let b = 0
          let c = 0
          if (axis === 0) {
            a = f
            b = g1
            c = g2
          } else if (axis === 1) {
            a = g1
            b = f
            c = g2
          } else {
            a = g1
            b = g2
            c = f
          }
          const coef = new Array<number>(words).fill(0)
          for (let t = 0; t < R; t++) {
            const tm = support[t]
            if (tm === undefined) continue
            const m1 = axis === 0 ? tm[1] : tm[0]
            const m2 = axis === 0 ? tm[2] : axis === 1 ? tm[2] : tm[1]
            const i1 = axis === 0 ? b : a
            const i2 = axis === 2 ? b : c
            if ((((m1 >> i1) & 1) & ((m2 >> i2) & 1)) !== 0) {
              coef[t >> 5] = ((coef[t >> 5] ?? 0) | (1 << (t & 31))) >>> 0
            }
          }
          rows.push({ coef, rhs: targetAt(a, b, c) })
        }
      }
      if (gaussSolve(R, rows) === null) ok = false
    }
    flags.push(ok)
  }
  return { u: flags[0] ?? false, v: flags[1] ?? false, w: flags[2] ?? false }
}

/* ------------------------------------------------------------ group actions */

function identityPerm(): CellPerm {
  return Array.from({ length: DIM }, (_, i) => i)
}

/** a after b (apply b first, then a). */
export function composePerm(a: CellPerm, b: CellPerm): CellPerm {
  const out = new Array<number>(DIM).fill(0)
  for (let c = 0; c < DIM; c++) out[c] = a[b[c] ?? c] ?? c
  return out
}

export function permKey(p: CellPerm): string {
  return p.join(",")
}

/** Closure of a set of generators under composition. */
export function groupClosure(gens: readonly CellPerm[]): CellPerm[] {
  const id = identityPerm()
  const seen = new Map<string, CellPerm>()
  seen.set(permKey(id), id)
  const stack: CellPerm[] = [id]
  while (stack.length > 0) {
    const g = stack.pop()
    if (g === undefined) break
    for (const h of gens) {
      const c = composePerm(h, g)
      const k = permKey(c)
      if (!seen.has(k)) {
        seen.set(k, c)
        stack.push(c)
      }
    }
  }
  return [...seen.values()].sort((a, b) => compareKeys(permKey(a), permKey(b)))
}

function permutations4(): number[][] {
  const out: number[][] = []
  const a = [0, 1, 2, 3]
  const rec = (k: number): void => {
    if (k === 4) {
      out.push([...a])
      return
    }
    for (let i = k; i < 4; i++) {
      const ak = a[k]
      const ai = a[i]
      if (ak === undefined || ai === undefined) continue
      a[k] = ai
      a[i] = ak
      rec(k + 1)
      a[k] = ak
      a[i] = ai
    }
  }
  rec(0)
  return out
}

/** Conjugation cell map M -> P M P^T for a coordinate permutation pi. */
export function permutationCellPerm(pi: readonly number[]): CellPerm {
  const out = new Array<number>(DIM).fill(0)
  for (let i = 0; i < PROBLEM_N; i++) {
    for (let j = 0; j < PROBLEM_N; j++) {
      const si = pi[i] ?? i
      const sj = pi[j] ?? j
      out[i * PROBLEM_N + j] = si * PROBLEM_N + sj
    }
  }
  return out
}

export const TRANSPOSE: CellPerm = (() => {
  const out = new Array<number>(DIM).fill(0)
  for (let i = 0; i < PROBLEM_N; i++) {
    for (let j = 0; j < PROBLEM_N; j++) out[i * PROBLEM_N + j] = j * PROBLEM_N + i
  }
  return out
})()

