/** R100's candidateHash (high and low 16-bit halves mixed separately). */
function campaignCandidateHash(terms: readonly Mask[]): string {
  let h = 0x811c9dc5
  const mix = (x: number): void => {
    h ^= x & 0xffff
    h = Math.imul(h, 0x01000193)
    h ^= (x >>> 16) & 0xffff
    h = Math.imul(h, 0x01000193)
  }
  for (const t of terms) {
    mix(t[0])
    mix(t[1])
    mix(t[2])
  }
  return (h >>> 0).toString(16).padStart(8, "0")
}

