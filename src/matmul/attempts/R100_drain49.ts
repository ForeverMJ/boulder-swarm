function bits(x: number): number[] {
  const out = new Array<number>(16).fill(0)
  for (let i = 0; i < 16; i++) out[i] = (x >> i) & 1
  return out
}

export function maskOf(v: readonly number[]): number {
  let m = 0
  for (let i = 0; i < 16 && i < v.length; i++) {
    if (((v[i] ?? 0) & 1) !== 0) m |= 1 << i
  }
  return m
}

function pop16(x: number): number {
  let v = x & 0xffff
  let n = 0
  while (v !== 0) {
    n += v & 1
    v >>>= 1
  }
  return n
}

function supp(x: number): number[] {
  const out: number[] = []
  for (let i = 0; i < 16; i++) {
    if (((x >> i) & 1) !== 0) out.push(i)
  }
  return out
}

const TARGET = new Uint8Array(4096)
{
  const loc = (bi: number, bj: number, q: number, qp: number): number =>
    (2 * bi + q) * 4 + (2 * bj + qp)
  for (let bi = 0; bi < 2; bi++) {
    for (let bj = 0; bj < 2; bj++) {
      for (let bk = 0; bk < 2; bk++) {
        for (let q = 0; q < 2; q++) {
          for (let qq = 0; qq < 2; qq++) {
            for (let qqq = 0; qqq < 2; qqq++) {
              TARGET[loc(bi, bj, q, qq) * 256 + loc(bj, bk, qq, qqq) * 16 + loc(bi, bk, q, qqq)] = 1
            }
          }
        }
      }
    }
  }
}

export function mismatches(terms: readonly FT[]): number {
  const got = new Uint8Array(4096)
  for (const t of terms) {
    const A = supp(t[0])
    const B = supp(t[1])
    const C = supp(t[2])
    for (const a of A) {
      for (const b of B) {
        for (const c of C) got[a * 256 + b * 16 + c] = (got[a * 256 + b * 16 + c] ?? 0) ^ 1
      }
    }
  }
  let mm = 0
  for (let i = 0; i < 4096; i++) {
    if (got[i] !== (TARGET[i] ?? 0)) mm++
  }
  return mm
}

function sumCells(terms: readonly FT[], idx: readonly number[]): Uint8Array {
  const out = new Uint8Array(4096)
  for (const k of idx) {
    const t = terms[k]
    if (t === undefined) continue
    const A = supp(t[0])
    const B = supp(t[1])
    const C = supp(t[2])
    for (const a of A) {
      for (const b of B) {
        for (const c of C) out[a * 256 + b * 16 + c] = (out[a * 256 + b * 16 + c] ?? 0) ^ 1
      }
    }
  }
  return out
}

function f2Witness(s: Uint8Array): FT | null {
  let a0 = -1
  let b0 = -1
  let c0 = -1
  for (let a = 0; a < 16 && a0 < 0; a++) {
    for (let b = 0; b < 16 && a0 < 0; b++) {
      for (let c = 0; c < 16; c++) {
        if (s[a * 256 + b * 16 + c] !== 0) {
          a0 = a
          b0 = b
          c0 = c
          break
        }
      }
    }
  }
  if (a0 < 0) return null
  let P = 0
  let Q = 0
  let R = 0
  for (let a = 0; a < 16; a++) {
    if ((s[a * 256 + b0 * 16 + c0] ?? 0) !== 0) P |= 1 << a
  }
  for (let b = 0; b < 16; b++) {
    if ((s[a0 * 256 + b * 16 + c0] ?? 0) !== 0) Q |= 1 << b
  }
  for (let c = 0; c < 16; c++) {
    if ((s[a0 * 256 + b0 * 16 + c] ?? 0) !== 0) R |= 1 << c
  }
  for (let a = 0; a < 16; a++) {
    if (((P >> a) & 1) === 0) continue
    for (let b = 0; b < 16; b++) {
      if (((Q >> b) & 1) === 0) continue
      for (let c = 0; c < 16; c++) {
        const want = (R >> c) & 1
        if (((s[a * 256 + b * 16 + c] ?? 0) !== 0 ? 1 : 0) !== want) return null
      }
    }
  }
  let ones = 0
  for (let i = 0; i < 4096; i++) ones += s[i] ?? 0
  if (ones !== pop16(P) * pop16(Q) * pop16(R)) return null
  return [P, Q, R]
}

/** Stable canonical hash over F_2 masks (matches R99-drain fnv). */
export function fnv(terms: readonly FT[]): string {
  let h = 0x811c9dc5
  for (const t of terms) {
    for (const x of t) {
      h ^= (x & 0xffff) + 0x9e37
      h = Math.imul(h, 0x01000193) >>> 0
    }
  }
  return (h >>> 0).toString(16).padStart(8, "0")
}

export function termsOf(start: StartState): FT[] {
  return start.masks.map((m) => [m[0] ?? 0, m[1] ?? 0, m[2] ?? 0] as FT)
}

export function schemeOf(terms: readonly FT[]): Scheme {
  return {
    n: N,
    triples: terms.map((t) => ({ u: bits(t[0]), v: bits(t[1]), w: bits(t[2]) })),
  }
}

export function vecOf(terms: readonly FT[]): number[][][] {
  return terms.map((t) => [bits(t[0]), bits(t[1]), bits(t[2])])
}

export function isExact(terms: readonly FT[]): boolean {
  return mismatches(terms) === 0
}

export function mulberry(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** Greedy exact F_2 drain: annihilate + merge2/merge3. Mutates terms. */
export function drain(terms: FT[], allowTriple: boolean): string[] {
  const chain: string[] = []
  for (let guard = 0; guard < 8; guard++) {
    let hit: { idx: number[]; m: FT } | null = null
    outer1: for (let i = 0; i < terms.length && hit === null; i++) {
      for (let j = i + 1; j < terms.length; j++) {
        const s = sumCells(terms, [i, j])
        let any = false
        for (let k = 0; k < 4096; k++) {
          if ((s[k] ?? 0) !== 0) {
            any = true
            break
          }
        }
        if (!any) {
          hit = { idx: [i, j], m: [0, 0, 0] }
          break outer1
        }
      }
    }
    if (hit === null) {
      outer2: for (let i = 0; i < terms.length && hit === null; i++) {
        for (let j = i + 1; j < terms.length; j++) {
          const m = f2Witness(sumCells(terms, [i, j]))
          if (m !== null) {
            hit = { idx: [i, j], m }
            break outer2
          }
        }
      }
    }
    if (hit === null && allowTriple && terms.length <= 56) {
      outer3: for (let i = 0; i < terms.length && hit === null; i++) {
        for (let j = i + 1; j < terms.length && hit === null; j++) {
          for (let k = j + 1; k < terms.length; k++) {
            const m = f2Witness(sumCells(terms, [i, j, k]))
            if (m !== null) {
              hit = { idx: [i, j, k], m }
              break outer3
            }
          }
        }
      }
    }
    if (hit === null) break
    const before = terms.length
    const rm = new Set(hit.idx)
    const nt = terms.filter((_, k) => !rm.has(k))
    if (hit.m[0] !== 0) nt.push(hit.m)
    terms.length = 0
    terms.push(...nt)
    chain.push(`m${hit.idx.length}:${before}->${terms.length}`)
  }
  if (!isExact(terms)) chain.push("BROKEN")
  return chain
}

/** F_2 shear on a pair sharing exactly one axis. Returns true if moved. */
export function f2Flip(terms: FT[], i: number, j: number, rnd: () => number): boolean {
  const ti = terms[i]
  const tj = terms[j]
  if (ti === undefined || tj === undefined || i === j) return false
  const sh: number[] = []
  for (let a = 0; a < 3; a++) {
    if (ti[a] === tj[a]) sh.push(a)
  }
  if (sh.length === 0) return false
  const ax = sh[Math.floor(rnd() * sh.length)] ?? 0
  if (ax === 0) {
    const nv = ti[1] ^ tj[1]
    const nw = tj[2] ^ ti[2]
    if (nv === 0 || nw === 0) return false
    terms[i] = [ti[0], nv, ti[2]]
    terms[j] = [tj[0], tj[1], nw]
  } else if (ax === 1) {
    const nw = ti[2] ^ tj[2]
    const nu = tj[0] ^ ti[0]
    if (nw === 0 || nu === 0) return false
    terms[i] = [ti[0], ti[1], nw]
    terms[j] = [nu, tj[1], tj[2]]
  } else {
    const nu = ti[0] ^ tj[0]
    const nv = ti[1] ^ tj[1]
    if (nu === 0 || nv === 0) return false
    terms[i] = [nu, nv, ti[2]]
    terms[j] = [tj[0], tj[1], tj[2]]
  }
  return true
}

export function f2Split(terms: FT[], i: number, rnd: () => number): boolean {
  const t = terms[i]
  if (t === undefined) return false
  const ax = Math.floor(rnd() * 3)
  const f = t[ax] ?? 0
  const nz = supp(f)
  if (nz.length < 2) return false
  let f1 = 0
  let f2 = 0
  for (const p of nz) {
    if (rnd() < 0.5) f1 |= 1 << p
    else f2 |= 1 << p
  }
  if (f1 === 0 || f2 === 0) return false
  const c1: FT = [t[0], t[1], t[2]]
  const c2: FT = [t[0], t[1], t[2]]
  c1[ax] = f1
  c2[ax] = f2
  terms[i] = c1
  terms.push(c2)
  return true
}

/**
 * Deterministic meld: alternating-halves child of two exact parents,
 * deduplicated, then drained back toward exactness. Returns the child and
 * its drain chain (chain includes BROKEN when the child never re-lands
 * exact — the caller discards such children, never checkpoints them).
 */
export function meld(a: readonly FT[], b: readonly FT[], rnd: () => number): { child: FT[]; chain: string[] } {
  const child: FT[] = []
  const seen = new Set<string>()
  const n = Math.max(a.length, b.length)
  for (let k = 0; k < n; k++) {
    const src = k % 2 === 0 ? (a[k] ?? b[k % (b.length === 0 ? 1 : b.length)]) : (b[k] ?? a[k % (a.length === 0 ? 1 : a.length)])
    if (src === undefined) continue
    const key = `${src[0]},${src[1]},${src[2]}`
    if (seen.has(key)) continue
    seen.add(key)
    child.push([src[0], src[1], src[2]])
  }
  // deterministic micro-perturbation so distinct seeds explore distinct kids
  for (let f = 0; f < 8; f++) {
    if (child.length < 2) break
    const i = Math.floor(rnd() * child.length)
    let j = Math.floor(rnd() * (child.length - 1))
    if (j >= i) j++
    f2Flip(child, i, j, rnd)
  }
  const chain = drain(child, false)
  return { child, chain: ["meld", ...chain] }
}

/**
 * The goalCheckA gate path for one candidate scheme: F_2 ground truth
 * (verifyMod2) fed into the M8 predicate (goalSatisfiedA). Returns the
 * winning entry, or undefined while the gate stays red.
 */
export function gateCheckA(candidate: Scheme, file: string): GoalEntry | undefined {
  const v = verifyMod2(candidate)
  const entry: GoalEntry = { file, n: candidate.n, correct: v.correct, rank: v.rank, mismatches: v.mismatches }
  return goalSatisfiedA([entry])
}

export type DrainOutcome = {
  readonly bestRank: number
  readonly bestHash: string
  readonly witness: boolean
  readonly iters: number
  readonly merges: number
  readonly flips: number
  readonly melds: number
}

/**
 * Bounded deterministic drain/meld from one exact start. Pure (no fs)
 * except via onBest, so tests stay fast. Only exact (mm 0) improvements
 * are reported via onBest; witness is true only for a gate-verified
 * rank<=47 candidate (verifyMod2 AND the goalCheckA path agree).
 */
export function boundedDrain(
  start: FT[],
  rnd: () => number,
  maxIters: number,
  onBest: (terms: FT[], chain: string[]) => void,
): DrainOutcome {
  let cur = start.map((t) => [...t] as FT)
  let best = cur.map((t) => [...t] as FT)
  let bestRank = cur.length
  let bestHash = fnv(cur)
  let merges = 0
  let flips = 0
  let melds = 0
  let witness = false
  let iters = 0
  onBest(best, ["replay"])
  {
    const work = best.map((t) => [...t] as FT)
    const chain = drain(work, true)
    if (!chain.includes("BROKEN") && work.length < bestRank) {
      merges++
      best = work.map((t) => [...t] as FT)
      bestRank = work.length
      bestHash = fnv(best)
      onBest(best, [...chain, "drain-first"])
      if (bestRank <= TARGET_RANK && gateCheckA(schemeOf(best), "R100_drain49.ts") !== undefined) {
        return { bestRank, bestHash, witness: true, iters, merges, flips, melds }
      }
      cur = best.map((t) => [...t] as FT)
    }
  }
  for (let it = 0; it < maxIters; it++) {
    iters = it + 1
    if (it % 8 === 7) {
      // meld week: child of cur x best, drain back
      const { child, chain } = meld(cur, best, rnd)
      melds++
      if (!chain.includes("BROKEN") && child.length < bestRank && isExact(child)) {
        merges++
        best = child.map((t) => [...t] as FT)
        bestRank = child.length
        bestHash = fnv(best)
        onBest(best, chain)
        if (bestRank <= TARGET_RANK && gateCheckA(schemeOf(best), "R100_drain49.ts") !== undefined) {
          witness = true
          break
        }
        cur = best.map((t) => [...t] as FT)
        continue
      }
    }
    const probe = cur.map((t) => [...t] as FT)
    if (it % 4 === 3) {
      for (let k = 0; k < 2; k++) f2Split(probe, Math.floor(rnd() * probe.length), rnd)
    }
    for (let f = 0; f < 24; f++) {
      if (probe.length < 2) break
      const a = Math.floor(rnd() * probe.length)
      let b = Math.floor(rnd() * (probe.length - 1))
      if (b >= a) b++
      if (f2Flip(probe, a, b, rnd)) flips++
    }
    const pchain = drain(probe, false)
    if (pchain.includes("BROKEN")) continue
    if (!isExact(probe)) continue
    if (probe.length < bestRank) {
      merges++
      best = probe.map((t) => [...t] as FT)
      bestRank = probe.length
      bestHash = fnv(best)
      onBest(best, [...pchain, "flip-interleave"])
      if (bestRank <= TARGET_RANK && gateCheckA(schemeOf(best), "R100_drain49.ts") !== undefined) {
        witness = true
        break
      }
      cur = best.map((t) => [...t] as FT)
    }
  }
  return { bestRank, bestHash, witness, iters, merges, flips, melds }
}

function checkpointedHashes(): Set<string> {
  try {
    const text = readFileSync(NDJSON, "utf-8")
    const out = new Set<string>()
    for (const line of text.split("\n")) {
      if (line.trim() === "") continue
      try {
        const r = JSON.parse(line) as { hash?: unknown }
        if (typeof r.hash === "string") out.add(r.hash)
      } catch {
        continue
      }
    }
    return out
  } catch {
    return new Set<string>()
  }
}

function log(row: unknown): void {
  appendFileSync(NDJSON, `${JSON.stringify(row)}\n`, "utf-8")
}

