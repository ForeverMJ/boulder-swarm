/**
 * The coefficient-aware half of the second necessary condition, decided exactly.
 *
 * R61's flattening screen bounds the dimension of the axis slices; R62's box cover bounds the
 * number of support boxes. Both are coefficient-free: they cannot see the values. The
 * condition implemented here does see them, and it is the one R61 named as missing: "each
 * column of the residual coefficient matrix must also reshape to rank <= 1".
 *
 * THE CONDITION. Write D = M - sum(surviving) for the deficit, and suppose
 *
 *     D[a][b][c] = sum_{t=1..j} u_t[a] v_t[b] w_t[c].                                  (*)
 *
 * Flatten (*) along axis c: D_c[(a,b)][c] = sum_t (u_t (x) v_t)[(a,b)] w_t[c]. So
 *
 *     col(D_c) is contained in col(X),  X = [ x_1 | ... | x_j ],  x_t = u_t (x) v_t,
 *
 * and each column x_t of X reshapes to a 3x3 matrix of rank exactly 1 (rank 0 only for a
 * degenerate term). Writing S_c for the span of all columns of all D_c:
 *
 *   (C1) dim S_c <= j for every axis c, and
 *   (C2) if dim S_c == j then col(X) == S_c exactly, so S_c must be spanned by j linearly
 *        independent vectors each of which reshapes to rank <= 1.                   <== THIS
 *
 * (C2) is the coefficient-aware half. The rank-1 reshaped vectors inside a d-dimensional
 * subspace of Q^9 are the intersection of that subspace with the Segre variety: the zeros of the
 * nine 2x2 minors of M(lambda) = sum_i lambda_i M_i, which are nine homogeneous quadrics in
 * lambda. Deciding whether S_c is spanned by d of them is a quadratic-form problem, and the
 * regimes where that decision is COMPLETE (never a sample) are:
 *
 *   d = 1: one projective point (1); it survives iff every minor coefficient vanishes.
 *   d = 2: P^1 is the chart y = 1 plus the single point (1,0) at y = 0, and on the chart the
 *           first non-degenerate conic has at most two rational roots, found exactly by
 *           discriminant plus a rational-square test, with the other eight filtering them.
 *           Both charts are solved, so the point list is exhaustive and `complete` is true.
 *   d = 3: NOT complete. When a 3-dimensional span is generated by rank-1 matrices, the Segre
 *           intersection can be a positive-dimensional curve in P^2; enumerating the roots of a
 *           single conic then returns a couple of points of a set whose rank-1 members are
 *           precisely the ones that matter. Several charts are still enumerated so the common
 *           case finds its witnesses, but `complete` is false and a `spanned: false` at d = 3 is
 *           NOT a refutation.
 *   d >= 4: a chart leaves at least three free parameters and the minors are no longer
 *           degree-limited, so a complete solve needs a Groebner basis. `complete` is false.
 *
 * Honest scope. A refutation is admissible only when `complete` is true, i.e. only at d <= 2.
 * Such a refutation is exact: S_c admits no spanning set of rank-1 reshaped vectors, so (*) is
 * impossible over Q, hence over Z, hence over every field. It is NOT a claim about rank 22
 * itself. `complete: false` carries no negative information whatsoever.
 *
 * Two further limits, both load-bearing. First, (C2) is only FORCED when dim S_c == j: if
 * dim S_c < j then col(X) is a strictly larger unknown space and S_c need not itself be spanned
 * by rank-1 vectors, so a caller must never read a refutation off an axis whose dim is below j.
 * Second, exactness. Everything here is rational Gaussian elimination and integer square roots
 * over BigInt. No float is compared for equality anywhere, and no float decides membership in a
 * variety.
 */

import { fDiv, fMul, fOne, fSub, fZero, isZero, rref } from "./rational"
import type { Fraction } from "./rational"

export const DIM9 = 9

const PAIRS: readonly (readonly [number, number])[] = (() => {
  const out: (readonly [number, number])[] = []
  for (let i = 0; i < DIM9; i += 1) for (let k = i + 1; k < DIM9; k += 1) out.push([i, k])
  return out
})()

// -------------------------------------------------------------------------------------
// Rational helpers local to this file. rational.ts has no fAdd; keeping these here avoids
// touching a shared tool whose behaviour other rounds' tests judge.
// -------------------------------------------------------------------------------------

export function fAdd(a: Fraction, b: Fraction): Fraction {
  return reduce(a.n * b.d + b.n * a.d, a.d * b.d)
}

export function reduce(n: bigint, d: bigint): Fraction {
  if (d === 0n) throw new RangeError("zero denominator")
  const sign = d < 0n ? -1n : 1n
  let nn = n * sign
  let dd = d * sign
  if (nn === 0n) return fZero()
  let x = nn < 0n ? -nn : nn
  let y = dd
  while (y !== 0n) {
    const t = x % y
    x = y
    y = t
  }
  if (x > 1n) {
    nn /= x
    dd /= x
  }
  return { n: nn, d: dd }
}

export function fInt(n: number): Fraction {
  return reduce(BigInt(n), 1n)
}

export function fNeg(a: Fraction): Fraction {
  return reduce(-a.n, a.d)
}

/** Exact integer square root of a non-negative bigint. */
export function isqrt(x: bigint): bigint {
  if (x < 0n) throw new RangeError("isqrt of a negative")
  if (x < 4n) return x
  let lo = 2n
  let hi = x
  while (lo <= hi) {
    const mid = (lo + hi) / 2n
    const sq = mid * mid
    if (sq === x) return mid
    if (sq < x) lo = mid + 1n
    else hi = mid - 1n
  }
  return hi
}

function isRationalSquare(f: Fraction): boolean {
  if (f.n < 0n) return false
  const rn = isqrt(f.n)
  const rd = isqrt(f.d)
  return rn * rn === f.n && rd * rd === f.d
}

function sqrtExact(f: Fraction): Fraction | null {
  if (!isRationalSquare(f)) return null
  return reduce(isqrt(f.n), isqrt(f.d))
}

/** -1, 0 or 1 according to the sign of a rational. */
export function signOf(f: Fraction): -1 | 0 | 1 {
  if (isZero(f)) return 0
  return f.n < 0n ? -1 : 1
}

